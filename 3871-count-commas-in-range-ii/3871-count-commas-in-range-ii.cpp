class Solution {
public:
    long long countCommas(long long n) {

        if (n <= 999) {
            return 0;
        }

        else if (n <= 999999) {
            return (n - 1000 + 1) * 1;
        }

        else if (n <= 999999999) {
            return (999999 - 1000 + 1) * 1
                   + (n - 1000000 + 1) * 2;
        }

        else if (n <= 999999999999) {
            return (999999 - 1000 + 1) * 1
                   + (999999999 - 1000000 + 1) * 2
                   + (n - 1000000000 + 1) * 3;
        }

        else if (n <= 999999999999999) {
            return (999999 - 1000 + 1) * 1
                   + (999999999 - 1000000 + 1) * 2
                   + (999999999999 - 1000000000 + 1) * 3
                   + (n - 1000000000000 + 1) * 4;
        }

        else {
            return (999999 - 1000 + 1) * 1
                   + (999999999 - 1000000 + 1) * 2
                   + (999999999999 - 1000000000 + 1) * 3
                   + (999999999999999 - 1000000000000 + 1) * 4
                   + (n - 1000000000000000 + 1) * 5;
        }
    }
};